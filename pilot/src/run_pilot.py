"""Phase A end-to-end pilot: mock simulator, committed ledger, mini-SR,
EES shard targeting, forget + scope-limit with verification.

Scenario (04_experimental_design_v2.md, Phase C rehearsed in miniature):
  - 5 committed batches from a coverage design (every x-band x T-band regime
    sampled twice; k=1 loss tolerance).
  - Batch B3 is generated by a biased party (kappa scaled 0.72): must be
    caught and FORGOTTEN (exact clean retrain, verified).
  - Above 1000 K the world is richer than the law: data are valid; the
    regime must be SCOPE-LIMITED, not forgotten (discovery preservation).
  - Null campaign control: same pipeline, no fault; nothing should fire.

Run:  python run_pilot.py <outdir>
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

from ledger import Ledger
from minisr import ensemble, fit_front, predict, select_model, support_region
from simulator import kappa_model_ideal, run_batch, seed_design
import ees

FAULT_BATCH = "B3"
FAULT_SCALE = 0.72
FORGET_Z = 3.0          # batch offset threshold, in units of batch-mean noise
ANOM_T = 1000.0


def split_batches(rows, n_batches=5):
    rng = np.random.default_rng(11)
    order = rng.permutation(len(rows))
    return {f"B{i+1}": [rows[j] for j in order[i::n_batches]]
            for i in range(n_batches)}


def campaign(outdir: Path, inject_fault: bool, tag: str) -> dict:
    led = Ledger(outdir / f"ledger_{tag}.jsonl")
    batches_design = split_batches(seed_design(reps=2))

    # 1. Commit every batch design BEFORE execution (pre-registration)
    for bid, rows in batches_design.items():
        led.commit_batch(f"{tag}:{bid}", rows)

    # 2. Execute
    results = {}
    for i, (bid, rows) in enumerate(batches_design.items()):
        scale = FAULT_SCALE if (inject_fault and bid == FAULT_BATCH) else 1.0
        res = run_batch(rows, seed=100 + i, fault_scale=scale)
        results[bid] = res
        led.append("batch_result", {"batch_id": f"{tag}:{bid}",
                                    "n": len(res),
                                    "fault_injected_hidden": None})
    all_rows = [r for rows in results.values() for r in rows]

    # 3. Fit + claim
    front = fit_front(all_rows)
    model = select_model(front, len(all_rows))
    led.append("claim", {"law": model["names"], "coefs": model["coefs"],
                         "complexity": model["complexity"], "mse": model["mse"]})

    # 4. Passports + shard priorities per regime
    term_freq, _, _ = ensemble(all_rows)
    regimes = ees.regime_map(all_rows)
    R = ees.shard_priority(regimes, model, all_rows)
    hi = {reg: r for reg, r in R.items() if r > 0.5}

    # 5. Hypergraph transversal: hyperedge per high-priority claim = its
    # regime plus the other regimes fed by the batch that dominates it
    hyperedges = {}
    for reg in hi:
        rows = regimes[reg]
        dom_batch = max(results, key=lambda b: sum(r in results[b] for r in rows))
        span = {ees.regime_of(r["x"], r["T"]) for r in results[dom_batch]}
        hyperedges[f"claim@{reg}"] = span | {reg}
    greedy = ees.greedy_transversal(hyperedges) if hyperedges else []
    exact = ees.exact_transversal_size(hyperedges) if hyperedges else 0
    led.append("shard_action_design", {"targets": greedy,
                                       "greedy_size": len(greedy),
                                       "exact_min_size": exact})

    # 6. Shard actions: independent re-measurement of targeted regimes
    #    (fresh seeds, unbiased party)
    recheck_rows = [r for reg in greedy for r in
                    ({"x": rr["x"], "T": rr["T"]} for rr in regimes[reg])]
    recheck = run_batch(recheck_rows, seed=999) if recheck_rows else []
    led.append("shard_action_result", {"n": len(recheck)})

    # 7. Diagnose: batch-coherent offset -> forget; regime-coherent
    #    (present in re-measurement too) -> scope-limit
    report = ees.batch_residual_report(results, model)
    noise = float(np.std([v for v in report.values()]))
    ops = []
    data_now = all_rows
    for bid, off in sorted(report.items(), key=lambda kv: kv[1]):
        others = [v for b, v in report.items() if b != bid]
        z = abs(off - np.mean(others)) / (np.std(others) + 1e-9)
        if z > FORGET_Z:
            op = ees.op_forget(data_now, results[bid])
            data_now = op["data"]
            model = op["model"]
            ops.append({"batch": bid, "z": round(float(z), 2), **{
                k: op[k] for k in ("op", "n_removed", "n_kept", "evidence")}})
            led.append("shard_operation", ops[-1])

    # Valid-anomaly check: residual vs ideal law in T>1000 regimes, using
    # re-measured (independent) data only
    anom_res = [(r["kappa"] - kappa_model_ideal(r["x"], r["T"])) /
                kappa_model_ideal(r["x"], r["T"])
                for r in recheck if r["T"] > ANOM_T]
    scope_limited = False
    if anom_res and np.mean(anom_res) < -0.1:
        op = ees.op_scope_limit(model, {"x": [0, 1], "T": [300, ANOM_T]})
        led.append("shard_operation", {"op": "scope-limit",
                                       "domain": op["validity_domain"],
                                       "mean_anomaly_residual":
                                           round(float(np.mean(anom_res)), 3)})
        scope_limited = True

    # 8. Verification: forget == retrain-from-scratch on clean data?
    verify = None
    if ops:
        clean = [r for bid, rows in results.items() if bid != FAULT_BATCH
                 for r in rows]
        scratch = select_model(fit_front(clean), len(clean))
        refit = select_model(fit_front(data_now), len(data_now))
        verify = {
            "same_terms": scratch["names"] == refit["names"],
            "max_coef_delta": float(max(abs(a - b) for a, b in
                                        zip(scratch["coefs"], refit["coefs"]))),
            "ledger_chain_valid": led.verify_chain(),
        }
        led.append("shard_verification", verify)

    return {
        "tag": tag, "n_rows": len(all_rows),
        "selected_law": {"terms": model["names"],
                         "coefs": [round(c, 8) for c in model["coefs"]],
                         "mse": model["mse"]},
        "term_front_frequency": term_freq,
        "batch_offsets": {k: round(v, 4) for k, v in report.items()},
        "high_priority_regimes": {k: round(v, 3) for k, v in hi.items()},
        "transversal": {"greedy": greedy, "greedy_size": len(greedy),
                        "exact_min_size": exact},
        "forget_ops": [{k: o[k] for k in ("batch", "z", "n_removed")}
                       for o in ops],
        "scope_limited_above_1000K": scope_limited,
        "verification": verify,
        "ledger_entries": len(led.entries),
        "ledger_chain_valid": led.verify_chain(),
    }


def main():
    outdir = Path(sys.argv[1] if len(sys.argv) > 1 else "results")
    outdir.mkdir(parents=True, exist_ok=True)
    fault_run = campaign(outdir, inject_fault=True, tag="fault")
    null_run = campaign(outdir, inject_fault=False, tag="null")
    summary = {
        "fault_campaign": fault_run,
        "null_campaign": null_run,
        "checks": {
            "fault_batch_caught": any(o["batch"] == FAULT_BATCH
                                      for o in fault_run["forget_ops"]),
            "no_extra_forgets": len(fault_run["forget_ops"]) == 1,
            "anomaly_scope_limited_not_forgotten":
                fault_run["scope_limited_above_1000K"],
            "null_no_forgets": len(null_run["forget_ops"]) == 0,
            "forget_verified_exact":
                bool(fault_run["verification"] and
                     fault_run["verification"]["same_terms"] and
                     fault_run["verification"]["max_coef_delta"] < 1e-9),
            "greedy_transversal_optimal":
                fault_run["transversal"]["greedy_size"] ==
                fault_run["transversal"]["exact_min_size"],
        },
    }
    (outdir / "pilot_summary.json").write_text(json.dumps(summary, indent=2))
    print(json.dumps(summary["checks"], indent=2))
    print("law:", fault_run["selected_law"]["terms"],
          "| null law:", null_run["selected_law"]["terms"])


if __name__ == "__main__":
    main()
